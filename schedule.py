from datetime import date, timedelta
from dataclasses import dataclass
from typing import Optional


# ============================================================
# МОДЕЛЬ ПАРЫ
# ============================================================

@dataclass
class Lesson:
    number: int
    subject: str
    teacher: Optional[str] = None
    room: Optional[str] = None

    # Дата начала действия пары
    start_date: Optional[date] = None

    # Дата окончания действия пары
    end_date: Optional[date] = None

    # Только конкретные даты
    specific_dates: Optional[list[date]] = None

    def is_active(self, target_date: date) -> bool:
        """
        Проверяет, действует ли эта пара в указанную дату.
        """

        # Если указаны конкретные даты
        if self.specific_dates is not None:
            return target_date in self.specific_dates

        # Проверка даты начала
        if self.start_date is not None:
            if target_date < self.start_date:
                return False

        # Проверка даты окончания
        if self.end_date is not None:
            if target_date > self.end_date:
                return False

        return True


