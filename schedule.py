WEEKDAYS = [
    "Понедельник",
    "Вторник",
    "Среда",
    "Четверг",
    "Пятница",
    "Суббота",
    "Воскресенье"
]


def get_weekday_name(target_date: date) -> str:
    return WEEKDAYS[target_date.weekday()]


# ============================================================
# ПОЛУЧЕНИЕ РАСПИСАНИЯ НА ДЕНЬ
# ============================================================

def get_lessons(target_date: date) -> list[Lesson]:

    weekday = get_weekday_name(target_date)
    week_type = get_week_type(target_date)

    day_schedule = SCHEDULE.get(weekday)

    if not day_schedule:
        return []

    # Четверг, пятница и выходные
    if "Общая" in day_schedule:
        lessons = day_schedule["Общая"]

    else:
        lessons = day_schedule.get(week_type, [])

    # Убираем предметы, которые ещё не начались
    # или уже закончились.
    active_lessons = []

    for item in lessons:

        if item.is_active(target_date):
            active_lessons.append(item)

    return active_lessons