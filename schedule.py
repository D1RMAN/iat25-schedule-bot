ANCHOR_DATE = date(2026, 10, 5)

# 05.10.2026 — ЧЁТНАЯ
ANCHOR_WEEK_TYPE = "Чётная"


def get_week_type(target_date: date) -> str:
    """
    05.10.2026–11.10.2026 = Чётная
    12.10.2026–18.10.2026 = Нечётная
    19.10.2026–25.10.2026 = Чётная
    и т.д.
    """

    days_difference = (target_date - ANCHOR_DATE).days

    week_number = days_difference // 7

    if week_number % 2 == 0:
        return "Чётная"

    return "Нечётная"


# ============================================================
# УТИЛИТЫ
# ============================================================

def d(day: int, month: int, year: int = 2026) -> date:
    return date(year, month, day)


def lesson(
    number,
    subject,
    teacher=None,
    room=None,
    start=None,
    end=None,
    specific_dates=None
):
    return Lesson(
        number=number,
        subject=subject,
        teacher=teacher,
        room=room,
        start_date=start,
        end_date=end,
        specific_dates=specific_dates
    )


